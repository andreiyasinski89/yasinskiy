    // attributes
    ATTRS.forEach(function (a) {
      var n = document.querySelector(a[0]); if (n && n.hasAttribute(a[1])) n.setAttribute(a[1], t(a[2]));  // only attributes that already exist
    });
    // document-level
    document.title = t(isIndex ? 'page.title' : 'privacy.title');
    var set = function (sel, attr, v) { var n = document.querySelector(sel); if (n) n.setAttribute(attr, v); };
    set('meta[name="description"]', 'content', t('page.desc'));
    set('meta[property="og:title"]', 'content', t('og.title'));
    set('meta[property="og:description"]', 'content', t('og.desc'));
    set('meta[property="og:locale"]', 'content', OG_LOCALE[l]);
    // hero
    if (isIndex) buildH1();
    // misc
    ['year', 'y'].forEach(function (id) { var n = document.getElementById(id); if (n) n.textContent = new Date().getFullYear(); });
